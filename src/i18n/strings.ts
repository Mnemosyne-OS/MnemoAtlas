/** de / pt / ru / zh are not written yet: those locales read English. */
const DICTS: Record<Lang, Dict> = { en, fr, es, de: {}, pt: {}, ru: {}, zh: {} };

export function isLang(x: unknown): x is Lang {
  return typeof x === 'string' && (LANGS as readonly string[]).includes(x);
}

/**
 * One string, in one language, with `{placeholders}` filled.
 *
 * A key missing from a locale falls back to English rather than rendering the
 * key itself: `review.tooSmall` on screen is worse than an English sentence,
 * and it is the failure mode nobody notices in the language they do not read.
 */
export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  const s = DICTS[lang]?.[key] ?? en[key];
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (whole, name: string) =>
    // An unknown placeholder is left as it is written rather than blanked:
    // a visible `{total}` gets reported, a silent gap does not.
    name in vars ? String(vars[name]) : whole);
}
